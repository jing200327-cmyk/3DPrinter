const { chromium } = require('C:/Users/MECHREVO/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.PRINTER_PAGE_URL || pathToFileURL(path.join(__dirname, '../index.html')).href;
const out = process.env.FIRMWARE_NETWORK_SHOTS;
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: process.env.PRINT_HOST_MAP ? [`--host-resolver-rules=${process.env.PRINT_HOST_MAP}`] : [] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const percent = () => page.locator('#firmware-progress-percent').textContent();
  const shot = async (selector, name) => {
    if (!out) return;
    fs.mkdirSync(out, { recursive: true });
    await page.locator(selector).screenshot({ path: path.join(out, name + '.png'), animations: 'disabled' });
  };
  const load = () => page.goto(base, { waitUntil: 'domcontentloaded' });
  const start = async () => {
    await page.locator('#firmware-banner').click();
    await page.locator('#open-firmware-version').click();
    await page.locator('#firmware-upgrade-now').click();
    await page.locator('#firmware-dialog-confirm').click();
    assert.equal(await page.locator('#firmware-progress-screen').isVisible(), true);
    assert.equal(await page.locator('#simulation-firmware-branches').evaluate(el => el.hidden), false, '升级期间展示固件分支列');
    assert.equal(await percent(), '0%');
  };
  try {
    await page.clock.install();
    await page.clock.pauseAt(new Date());
    await load();
    assert.equal(await page.locator('#simulation-firmware-branches').isVisible(), false);
    await start();
    await page.clock.runFor(2700);
    const held = await percent();
    assert.equal(held, '18%');
    await shot('#firmware-progress-screen', '01-firmware-downloading');
    await page.locator('#simulate-firmware-network-error').click();
    const dialog = page.locator('#firmware-network-dialog');
    const warning = page.locator('#firmware-network-warning');
    assert.equal(await dialog.isVisible(), true);
    assert.equal(await page.locator('#firmware-network-copy').textContent(), '当前网络环境差，固件包下载中断，请检查网络是否正常');
    assert.equal(await dialog.locator('button').count(), 1);
    assert.equal(await dialog.locator('button').textContent(), '确定');
    await page.clock.runFor(20000);
    assert.equal(await percent(), held, '确认前进度始终暂停');
    assert.equal(await page.locator('#firmware-done-screen').isVisible(), false);
    await shot('#firmware-progress-screen', '02-network-interrupted-dialog');
    await page.locator('#firmware-network-confirm').click();
    assert.equal(await dialog.isVisible(), false);
    assert.equal(await warning.isVisible(), true);
    assert.equal(await page.locator('#firmware-network-banner').textContent(), '当前网络环境差');
    await shot('#firmware-progress-screen', '03-persistent-network-warning');
    await page.clock.runFor(4000);
    assert.equal(await percent(), held, '恢复等待期间保持暂停');
    assert.equal(await warning.isVisible(), true, '网络差时提醒常驻');
    await page.clock.runFor(1300);
    assert.equal(await warning.isVisible(), false);
    assert(Number((await percent()).replace('%', '')) > 18, '恢复后从暂停值继续');
    await shot('#firmware-progress-screen', '04-network-recovered');
    await page.locator('#simulate-firmware-network-error').click();
    const heldAgain = await percent();
    await page.locator('#firmware-network-confirm').click();
    await page.clock.runFor(4000);
    assert.equal(await percent(), heldAgain, '重复异常不重置已有进度');
    await page.clock.runFor(22000);
    assert.equal(await page.locator('#firmware-done-screen').isVisible(), true);
    assert.equal(await percent(), '100%');
    assert.equal(await page.locator('#simulation-firmware-branches').isVisible(), false);
    assert.equal(await warning.isVisible(), false);
    await page.locator('#firmware-done-ok').click();
    assert.equal(await page.locator('#firmware-banner').isVisible(), false);
    // 离开升级页后，延迟恢复不能重新打开任何升级页面。
    await load();
    await start();
    await page.clock.runFor(600);
    await page.locator('#simulate-firmware-network-error').click();
    await page.locator('#firmware-network-confirm').click();
    await page.locator('#simulate-filament-empty').click();
    await page.clock.runFor(22000);
    assert.equal(await page.locator('#firmware-progress-screen').isVisible(), false);
    assert.equal(await page.locator('#firmware-done-screen').isVisible(), false);
    assert.equal(await warning.isVisible(), false);
    assert.equal(await page.locator('#simulation-firmware-branches').isVisible(), false);
    // 正常升级路径与手机端异常提醒。
    await load();
    await start();
    await page.clock.runFor(16000);
    assert.equal(await page.locator('#firmware-done-screen').isVisible(), true);
    await page.setViewportSize({ width: 375, height: 812 });
    await load();
    await start();
    await page.locator('#simulation-console > summary').click();
    await page.locator('#simulate-firmware-network-error').click();
    await page.locator('#firmware-network-confirm').click();
    await page.locator('#simulation-console > summary').click();
    for (const width of [375, 320]) {
      await page.setViewportSize({ width, height: 812 });
      assert.equal(await warning.isVisible(), true);
      const rect = await warning.boundingBox();
      assert(rect.x >= 0 && rect.x + rect.width <= width);
      const title = await warning.locator('h1').boundingBox();
      const number = await page.locator('#firmware-progress-percent').boundingBox();
      assert(title.y + title.height < number.y, '提醒与标题不遮挡百分比');
      await shot('#firmware-progress-screen', `05-mobile-warning-${width}`);
    }
    assert.deepEqual(errors, []);
    console.log('PASS: firmware interruption freezes progress; confirmation shows persistent warning; 5s recovery resumes; repeated errors, normal completion, cleanup and mobile layout verified');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
