const { chromium } = require('C:/Users/MECHREVO/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
const base = process.env.PRINTER_PAGE_URL || pathToFileURL(path.join(__dirname, '../index.html')).href;
const out = process.env.PRINT_FILAMENT_SHOTS;
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: process.env.PRINT_HOST_MAP ? [`--host-resolver-rules=${process.env.PRINT_HOST_MAP}`] : [] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const open = async query => {
    const url = new URL(base);
    Object.entries({ status: 'ready', screen: 'prepare-print', ...query }).forEach(([key, value]) => url.searchParams.set(key, value));
    await page.goto(url.href);
    await page.locator('#start-print').waitFor({ state: 'visible' });
  };
  const shot = async (selector, name) => {
    if (!out) return;
    fs.mkdirSync(out, { recursive: true });
    await page.locator(selector).screenshot({ path: path.join(out, name + '.png'), animations: 'disabled' });
  };
  try {
    await page.clock.install();
    await page.clock.pauseAt(new Date());
    await open({ filamentSensor: 'present', filamentFed: 'yes' });
    await page.locator('#prepare-plate-list [data-plate="2"] .plate-row-hit').click({ position: { x: 240, y: 12 } });
    await page.locator('#timelapse-toggle').click();
    await page.locator('#simulation-filament-sensor').selectOption('absent');
    assert.equal(await page.locator('#prepare-stage .prepare-material--empty').count(), 3, '无料时三盘均展示独立的耗材空态');
    assert.equal(await page.locator('#prepare-stage .prepare-mismatch:visible').count(), 3, '每盘右侧显示红色警示符号');
    assert.equal(await page.locator('#prepare-stage .prepare-spool').first().getAttribute('alt'), '未安装耗材');
    await page.clock.runFor(2000); // 截图前等待上一条操作提示自然消失。
    await shot('#prepare-print-screen', 'PRINT-D-02-empty-material');
    await page.locator('#start-print').click();
    const dialog = page.locator('#print-filament-required-dialog');
    assert.equal(await dialog.isVisible(), true);
    assert.equal(await page.locator('#print-filament-required-copy').textContent(), '当前打印机尚未安装耗材并进料，请在打印前进料');
    assert.equal(new URL(page.url()).searchParams.get('status'), 'ready', '无料不提交任务');
    await shot('#prepare-print-screen', 'PRINT-D-03-no-material-dialog');
    await page.locator('#print-filament-required-cancel').click();
    assert.equal(await page.locator('#prepare-plate-list [data-plate="2"]').getAttribute('aria-selected'), 'true');
    assert.equal(await page.locator('#timelapse-toggle').getAttribute('aria-checked'), 'false');
    await page.locator('#start-print').click();
    await page.locator('#print-filament-go-feed').click();
    assert.equal(await page.locator('#filament-guide-title').textContent(), '安装耗材');
    assert.equal(await page.locator('#prepare-print-screen').isVisible(), false);
    await page.locator('#filament-guide-back').click();
    assert.equal(await page.locator('#prepare-print-screen').isVisible(), true, '引导返回准备打印页');
    await page.locator('#start-print').click();
    await page.locator('#print-filament-go-feed').click();
    await page.locator('#simulation-filament-sensor').selectOption('present');
    await page.locator('#filament-guide-start').click();
    await page.clock.runFor(16000);
    await page.locator('#filament-operation-primary').click();
    assert.equal(await page.locator('#prepare-print-screen').isVisible(), true, '手动进料完成后返回原准备页');
    assert.equal(await page.locator('#simulation-filament-fed').inputValue(), 'yes');
    assert.equal(await page.locator('#prepare-stage .prepare-material--empty').count(), 0, '恢复有料图标与颜色匹配状态');
    assert.equal(await page.locator('#prepare-stage .prepare-mismatch:visible').count(), 1, '保留原绿色模型与蓝色耗材不匹配警示');
    await open({ filamentSensor: 'present', filamentFed: 'yes' });
    await page.locator('#simulation-filament-fed').selectOption('no');
    await page.locator('#start-print').click();
    await page.waitForURL(url => url.searchParams.get('status') === 'preparing' && !url.searchParams.has('screen'));
    assert.equal(await page.locator('#task-state').textContent(), '准备中');
    assert.equal(await page.locator('#preparation-label').textContent(), '进料中');
    assert.equal(await page.locator('#preparation-percent').isVisible(), false);
    assert.equal(await page.locator('#filament-operation-screen').isVisible(), false, '自动进料由工作台承载');
    assert.equal(await page.locator('#simulation-filament-fed').inputValue(), 'no');
    await shot('#device-page', 'PRINT-D-04-workbench-feeding');
    await shot('#task-panel', 'PRINT-D-04-feeding-panel');
    await page.clock.runFor(16000);
    assert.equal(await page.locator('#simulation-filament-fed').inputValue(), 'yes');
    assert.equal(await page.locator('#preparation-label').textContent(), '正在分析模型', '进料成功后继续原打印准备流程');
    await page.clock.runFor(10000);
    assert.equal(await page.locator('#preparation-label').textContent(), '升温中');
    await page.clock.runFor(16000);
    assert.equal(await page.locator('#task-state').textContent(), '打印中');
    await open({ filamentSensor: 'present', filamentFed: 'no' });
    await page.locator('#start-print').click();
    await page.waitForURL(url => url.searchParams.get('status') === 'preparing');
    await page.locator('#simulation-filament-sensor').selectOption('absent');
    await page.clock.runFor(45000);
    assert.notEqual(await page.locator('#task-state').textContent(), '打印中', '前置进料中断后不得继续进入打印');
    await open({ filamentSensor: 'present', filamentFed: 'yes' });
    await page.locator('#start-print').click();
    await page.waitForURL(url => url.searchParams.get('status') === 'preparing');
    assert.equal(await page.locator('#preparation-label').textContent(), '正在分析模型', '已进料跳过自动进料');
    await open({ filamentSensor: 'absent', filamentFed: 'yes' });
    await page.locator('#start-print').click();
    assert.equal(await dialog.isVisible(), true, '无料信号优先于已进料标记');
    await page.locator('#print-filament-required-cancel').click();
    for (const width of [320, 375]) {
      await page.setViewportSize({ width, height: 812 });
      await page.locator('#simulation-console').evaluate(el => el.open = false);
      assert.equal(await page.locator('#prepare-stage').evaluate(el => el.scrollWidth <= el.clientWidth), true);
      await shot('#prepare-print-screen', `empty-material-${width}`);
    }
    assert.deepEqual(errors, []);
    console.log('PASS: empty-state icons, start-print sensor gate, installation return, automatic feed before printing, fed-state persistence and responsive views');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
