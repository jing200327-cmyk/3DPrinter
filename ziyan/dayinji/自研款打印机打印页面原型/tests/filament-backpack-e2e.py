from playwright.sync_api import sync_playwright, expect
from pathlib import Path
import os

URL = os.environ.get('PRINTER_PAGE_URL', (Path(__file__).resolve().parents[1] / 'index.html').as_uri())
OUT = Path(os.environ.get('BACKPACK_SHOTS', str(Path(__file__).resolve().parent / '_backpack-shots')))
OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.clock.install()
    page.clock.pause_at(2000000000000)
    page.goto(URL)
    expect(page.locator('#simulation-filament-source')).to_be_visible(timeout=3000)
    page.select_option('#simulation-filament-source', 'backpack')
    expect(page.locator('.bp-slot')).to_have_count(4)
    expect(page.locator('.bp-slot:disabled')).to_have_count(4)
    expect(page.locator('#load-filament')).to_be_disabled()
    expect(page.locator('#unload-filament')).to_be_disabled()
    page.locator('.bp-edit').first.click()
    expect(page.locator('#toast')).to_have_text('当前无耗材')
    page.locator('.filament-panel').screenshot(path=str(OUT/'empty.png'))
    print('PASS: four empty slots, edit toast, disabled actions')
    page.locator('#simulate-filament-detected').click()
    expect(page.locator('#load-filament')).to_be_disabled()
    page.locator('.bp-slot').nth(0).click()
    expect(page.locator('.bp-slot.is-selected')).to_have_count(1)
    expect(page.locator('#load-filament')).to_be_enabled()
    expect(page.locator('#unload-filament')).to_be_disabled()
    page.locator('.filament-panel').screenshot(path=str(OUT/'selected.png'))
    page.select_option('#simulation-filament-sensor', 'absent')
    page.locator('#load-filament').click()
    expect(page.locator('#filament-guide-screen')).to_be_visible()
    page.locator('#filament-guide-start').click()
    expect(page.locator('#filament-not-detected-dialog')).to_be_visible()
    page.locator('#filament-not-detected-dialog button').click()
    page.select_option('#simulation-filament-sensor', 'present')
    page.locator('#filament-guide-start').click()
    page.locator('#filament-operation-back').click()
    expect(page.locator('#load-filament')).to_have_text('进料中...')
    expect(page.locator('#load-filament')).to_be_enabled()
    expect(page.locator('#unload-filament')).to_be_disabled()
    expect(page.locator('#filament-status')).to_have_text('1号料盘进料中')
    page.locator('.filament-panel').screenshot(path=str(OUT/'feeding.png'))
    page.locator('#load-filament').click()
    expect(page.locator('#filament-operation-screen')).to_be_visible()
    page.locator('#filament-operation-back').click()
    page.clock.run_for(16000)
    expect(page.locator('#filament-status')).to_have_text('1号料盘进料完成')
    expect(page.locator('#load-filament')).to_be_disabled()
    expect(page.locator('#unload-filament')).to_be_enabled()
    page.locator('#unload-filament').click()
    expect(page.locator('#filament-guide-title')).to_have_text('退出耗材')
    page.locator('#filament-guide-start').click()
    page.locator('#filament-operation-back').click()
    expect(page.locator('#unload-filament')).to_have_text('退料中...')
    expect(page.locator('#load-filament')).to_be_disabled()
    expect(page.locator('#filament-status')).to_have_text('1号料盘退料中')
    page.clock.run_for(16000)
    expect(page.locator('#filament-status')).to_have_text('1号料盘退料完成')
    expect(page.locator('#load-filament')).to_be_enabled()
    expect(page.locator('#unload-filament')).to_be_disabled()
    print('PASS: sensor gate, guidance, background progress, completion, mutual exclusion')
    page.select_option('#simulation-backpack-slot', '3')
    page.locator('#simulate-filament-detected').click()
    expect(page.locator('.bp-slot:enabled')).to_have_count(2)
    page.locator('.bp-slot').nth(3).click()
    expect(page.locator('.bp-slot.is-selected')).to_have_count(1)
    page.locator('#load-filament').click()
    page.locator('#filament-guide-start').click()
    page.clock.run_for(16000)
    page.locator('#filament-operation-primary').click()
    expect(page.locator('#filament-status')).to_have_text('4号料盘进料完成')
    page.locator('#unload-filament').click()
    page.locator('#filament-guide-start').click()
    page.locator('#filament-operation-primary').click()
    page.locator('#filament-cancel-confirm').click()
    expect(page.locator('#filament-status')).to_have_text('4号料盘进料完成')
    expect(page.locator('#unload-filament')).to_be_enabled()
    print('PASS: slot-specific completion, foreground finish, cancellation restores state')
    page.select_option('#simulation-filament-source', 'rack')
    expect(page.locator('#filament-panel-image')).to_be_visible()
    expect(page.locator('#load-filament')).to_be_enabled()
    expect(page.locator('#unload-filament')).to_be_enabled()
    page.select_option('#simulation-filament-source', 'backpack')
    expect(page.locator('#load-filament')).to_be_disabled()
    expect(page.locator('.bp-slot:enabled')).to_have_count(2)
    for width in [320, 768, 1024, 1440]:
        page.set_viewport_size({'width': width, 'height': 950})
        page.locator('.filament-panel').scroll_into_view_if_needed()
        page.locator('.filament-panel').screenshot(path=str(OUT/f'panel-{width}.png'))
    assert not errors, errors
    print('PASS: source restoration, slot persistence, responsive rendering, no page errors')
    browser.close()
