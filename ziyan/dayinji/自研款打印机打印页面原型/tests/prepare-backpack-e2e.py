from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import os
import tempfile

URL = os.environ.get('PRINTER_PAGE_URL', (Path(__file__).resolve().parents[1] / 'index.html').as_uri())
OUT = Path(os.environ.get('PREPARE_BACKPACK_SHOTS') or tempfile.mkdtemp(prefix='prepare-backpack-'))
OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(URL)
    page.select_option('#simulation-filament-source', 'backpack')
    page.locator('#explore-toys').click()
    page.locator('#explore-toys-anywhere').click()
    page.locator('#open-prepare-print').click()
    material = page.locator('#prepare-print-screen .prepare-material').first
    expect(material).to_have_class(__import__('re').compile('prepare-material--empty'))
    expect(material.locator('.prepare-backpack-trigger')).to_be_visible(timeout=3000)
    material.locator('.prepare-backpack-trigger').click()
    expect(page.locator('#backpack-material-picker')).to_be_visible()
    expect(page.locator('.bp-picker-slot')).to_have_count(4)
    expect(page.locator('.bp-picker-slot:disabled')).to_have_count(4)
    expect(page.locator('#backpack-material-confirm')).to_be_disabled()
    page.locator('#backpack-material-picker').screenshot(path=str(OUT/'empty.png'))
    page.locator('#backpack-material-close').click()
    print('PASS: preparation empty state, four empty slots, confirm disabled')
    page.locator('#simulate-filament-detected').click()
    expect(page.locator('#prepare-print-screen')).to_be_visible()
    expect(material).not_to_have_class(__import__('re').compile('prepare-material--empty'))
    expect(material.locator('.prepare-loaded-color')).to_have_text('蓝色')
    expect(material.locator('.prepare-mismatch')).to_be_hidden()
    material.locator('.prepare-backpack-trigger').click()
    expect(page.locator('.bp-picker-slot:enabled')).to_have_count(1)
    expect(page.locator('.bp-picker-slot').nth(0)).to_have_attribute('aria-checked','true')
    expect(page.locator('#backpack-material-warning')).to_be_hidden()
    page.locator('#backpack-material-close').click()
    # Color matching uses slot presence, independently of the nozzle sensor.
    page.select_option('#simulation-filament-sensor','absent')
    expect(material.locator('.prepare-loaded-color')).to_have_text('蓝色')
    page.select_option('#simulation-backpack-slot','2')
    page.locator('#simulate-filament-detected').click()
    green = page.locator('#prepare-print-screen .prepare-material').nth(2)
    expect(green.locator('.prepare-loaded-color')).to_have_text('绿色')
    expect(green.locator('.prepare-mismatch')).to_be_hidden()
    page.locator('#prepare-print-screen').screenshot(path=str(OUT/'matched.png'))
    green.locator('.prepare-backpack-trigger').click()
    expect(page.locator('.bp-picker-slot:enabled')).to_have_count(2)
    expect(page.locator('.bp-picker-slot').nth(2)).to_have_attribute('aria-checked','true')
    expect(page.locator('.bp-picker-presence')).to_have_text(['蓝色','空','绿色','空'])
    page.locator('.bp-picker-slot').nth(0).click()
    expect(page.locator('#backpack-material-warning')).to_have_text('颜色差异会导致耗材不匹配，请手动选择耗材')
    page.locator('#backpack-material-close').click()
    expect(green.locator('.prepare-loaded-color')).to_have_text('绿色')
    green.locator('.prepare-backpack-trigger').click()
    page.locator('.bp-picker-slot').nth(0).click()
    page.locator('#backpack-material-confirm').click()
    expect(green.locator('.prepare-loaded-color')).to_have_text('1号 蓝色')
    expect(green.locator('.prepare-loaded-color')).to_be_visible()
    expect(green.locator('.prepare-mismatch')).to_be_hidden()
    expect(green.locator('.prepare-backpack-spool')).to_be_visible()
    page.select_option('#simulation-filament-sensor','present')
    expect(green.locator('.prepare-mismatch')).to_be_hidden()
    page.locator('#prepare-print-screen').screenshot(path=str(OUT/'manually-confirmed.png'))
    green.locator('.prepare-backpack-trigger').click()
    expect(page.locator('#backpack-material-warning')).to_be_hidden()
    page.locator('.bp-picker-slot').nth(2).click()
    expect(page.locator('#backpack-material-warning')).to_be_hidden()
    page.locator('#backpack-material-confirm').click()
    expect(green.locator('.prepare-mismatch')).to_be_hidden()
    print('PASS: exact match, real slot colors, confirmation shows slot/color and clears warning, cancel preserves selection')
    # Remove the exact match and supply a nearby blue-purple color.
    page.select_option('#simulation-backpack-slot','0')
    page.select_option('#simulation-backpack-color','indigo')
    expect(material.locator('.prepare-loaded-color')).to_be_hidden()
    expect(material.locator('.prepare-backpack-spool')).to_be_hidden()
    expect(material.locator('.prepare-spool')).to_be_hidden()
    expect(material.locator('.prepare-mismatch')).to_be_visible()
    page.locator('#prepare-print-screen').screenshot(path=str(OUT/'mismatch-only-warning.png'))
    material.locator('.prepare-backpack-trigger').click()
    expect(page.locator('.bp-picker-slot').nth(0)).to_have_attribute('aria-checked','true')
    expect(page.locator('#backpack-material-warning')).to_be_visible()
    page.locator('.bp-picker-slot').nth(2).click()
    expect(page.locator('#backpack-material-warning')).to_be_visible()
    page.locator('#backpack-material-picker').screenshot(path=str(OUT/'mismatch-warning.png'))
    page.locator('#backpack-material-close').click()
    expect(material.locator('.prepare-mismatch')).to_be_visible()
    # A manual slot selection disappears only if that selected slot becomes empty.
    material.locator('.prepare-backpack-trigger').click()
    page.locator('.bp-picker-slot').nth(2).click()
    page.locator('#backpack-material-confirm').click()
    expect(material.locator('.prepare-loaded-color')).to_have_text('3号 绿色')
    expect(material.locator('.prepare-mismatch')).to_be_hidden()
    page.locator('#simulate-filament-empty').click()
    expect(material.locator('.prepare-loaded-color')).to_have_text('3号 绿色')
    page.select_option('#simulation-backpack-slot','2')
    page.select_option('#simulation-backpack-color','red')
    expect(material.locator('.prepare-mismatch')).to_be_visible()
    expect(material.locator('.prepare-loaded-color')).to_be_hidden()
    page.locator('#simulate-filament-empty').click()
    expect(material).to_have_class(__import__('re').compile('prepare-material--empty'))
    print('PASS: nearest color fallback, mismatch badge, live updates and invalidation')
    page.select_option('#simulation-filament-source','rack')
    expect(page.locator('#prepare-print-screen')).to_be_visible()
    expect(material.locator('.prepare-backpack-trigger')).to_have_count(0)
    page.select_option('#simulation-filament-source','backpack')
    page.select_option('#simulation-backpack-slot','3')
    page.select_option('#simulation-backpack-color','blue')
    page.locator('#simulate-filament-detected').click()
    expect(material.locator('.prepare-loaded-color')).to_have_text('蓝色')
    material.locator('.prepare-backpack-trigger').focus()
    page.keyboard.press('Enter')
    expect(page.locator('#backpack-material-picker')).to_be_visible()
    page.locator('.bp-picker-slot').nth(3).focus()
    page.keyboard.press('Enter')
    expect(page.locator('#backpack-material-picker')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.locator('#backpack-material-picker')).not_to_be_visible()
    page.emulate_media(reduced_motion='reduce')
    for width in [320, 768, 1440]:
        page.set_viewport_size({'width':width,'height':950})
        material.locator('.prepare-backpack-trigger').click()
        dialog = page.locator('#backpack-material-picker')
        expect(dialog).to_be_visible()
        rect = dialog.bounding_box()
        assert rect['x'] >= -1 and rect['x'] + rect['width'] <= width + 1, rect
        assert rect['y'] >= -1 and rect['y'] + rect['height'] <= 951, rect
        dialog.screenshot(path=str(OUT/f'picker-{width}.png'))
        page.locator('#backpack-material-close').click()
    assert not errors, errors
    print('PASS: source switching preserves preparation, keyboard and responsive drawer, no page errors')
    browser.close()
